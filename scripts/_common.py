def savefig(fig, name: str):
    config.FIGURES.mkdir(parents=True, exist_ok=True)
    fig.savefig(config.FIGURES / f"{name}.pdf")
    plt.close(fig)
    print(f"figure -> report/figures/{name}.pdf")


def write_tex(name: str, text: str):
    config.GENERATED.mkdir(parents=True, exist_ok=True)
    (config.GENERATED / f"{name}.tex").write_text(text)
    print(f"latex  -> report/generated/{name}.tex")


def macros(name: str, values: dict):
    r"""Write \newcommand macros so that every number in the report comes from a script."""
    lines = [f"% auto-generated by scripts; do not edit by hand"]
    for k, v in values.items():
        assert k.isalpha(), f"macro names must be letters only: {k}"
        lines.append(f"\\newcommand{{\\{k}}}{{{v}}}")
    write_tex(name, "\n".join(lines) + "\n")
